// Package extract reads the doc comments of a config struct, and of every type
// it reaches, from source - which is what a program does not carry at runtime -
// and writes them as Go source declaring [configdoc.Docs].
//
// It lives apart from configdoc so that a program rendering its config does not
// link the go toolchain packages this one needs.
package extract

import (
	"bytes"
	"cmp"
	"errors"
	"fmt"
	"go/ast"
	"go/constant"
	"go/format"
	"go/token"
	"go/types"
	"maps"
	"reflect"
	"slices"
	"strconv"
	"strings"

	"github.com/choopm/stdfx/configfx/configdoc"
	"golang.org/x/tools/go/packages"
)

// Options configures an extraction.
type Options struct {
	// Dir is the directory the packages are resolved from, the working
	// directory if empty
	Dir string

	// Func is the name of the function the generated source declares
	Func string

	// Package is the name of the package of the generated source
	Package string

	// SkipUntagged leaves out exported fields without a mapstructure tag,
	// see [configdoc.Docs.SkipUntagged]
	SkipUntagged bool

	// Type is the config struct as import path and name,
	// "example.com/app/server.Config"
	Type string
}

// Result is what an extraction found.
type Result struct {
	// Docs are the extracted docs
	Docs *configdoc.Docs

	// Missing are the fields without a doc comment, as "Type.Field" qualified
	// by their import path
	Missing []string
}

// Extract returns the docs of opts.Type and every type it reaches, or error.
func Extract(opts Options) (*Result, error) {
	pkgPath, typeName, ok := cutLast(opts.Type, ".")
	if !ok {
		return nil, fmt.Errorf("type %q is not of the form <import path>.<name>", opts.Type)
	}

	// pass 1: the types reachable from the config, from export data
	pkgs, err := packages.Load(&packages.Config{
		Dir:  opts.Dir,
		Mode: packages.NeedName | packages.NeedTypes | packages.NeedImports | packages.NeedDeps,
	}, pkgPath)
	if err != nil {
		return nil, fmt.Errorf("loading %s: %w", pkgPath, err)
	}
	if err := packageErrors(pkgs); err != nil {
		return nil, err
	}
	if len(pkgs) != 1 || pkgs[0].Types == nil {
		return nil, fmt.Errorf("loading %s: no such package", pkgPath)
	}
	obj := pkgs[0].Types.Scope().Lookup(typeName)
	if obj == nil {
		return nil, fmt.Errorf("%s: no such type", opts.Type)
	}

	w := &walker{
		enums:        map[string]map[string]*types.Named{},
		skipUntagged: opts.SkipUntagged,
		structs:      map[string]map[string]*types.Named{},
	}
	if err := w.walk(obj.Type()); err != nil {
		return nil, err
	}

	// pass 2: the source of the packages declaring them
	paths := slices.Sorted(maps.Keys(w.packages()))
	srcs, err := packages.Load(&packages.Config{
		Dir:  opts.Dir,
		Mode: packages.NeedName | packages.NeedFiles | packages.NeedSyntax | packages.NeedTypes | packages.NeedTypesInfo,
	}, paths...)
	if err != nil {
		return nil, fmt.Errorf("loading sources: %w", err)
	}
	if err := packageErrors(srcs); err != nil {
		return nil, err
	}

	result := &Result{
		Docs: &configdoc.Docs{
			Enums:  map[configdoc.TypeKey][]configdoc.Enum{},
			Fields: map[configdoc.Key]configdoc.Doc{},
			Types:  map[configdoc.TypeKey]string{},
		},
	}
	for _, src := range srcs {
		w.read(src, result)
	}
	slices.Sort(result.Missing)

	return result, nil
}

// Generate returns the Go source of a file in package opts.Package declaring
// the function opts.Func, which returns docs.
func Generate(opts Options, docs *configdoc.Docs) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by configdoc -type %s; DO NOT EDIT.\n\n", opts.Type)
	fmt.Fprintf(&b, "package %s\n\n", opts.Package)
	fmt.Fprintf(&b, "import \"github.com/choopm/stdfx/configfx/configdoc\"\n\n")
	fmt.Fprintf(&b, "// %s returns the docs extracted from the source of %s.\n", opts.Func, opts.Type)
	fmt.Fprintf(&b, "func %s() *configdoc.Docs {\n\treturn &configdoc.Docs{\n", opts.Func)

	fmt.Fprintf(&b, "\t\tEnums: map[configdoc.TypeKey][]configdoc.Enum{\n")
	for _, k := range sortedTypeKeys(docs.Enums) {
		fmt.Fprintf(&b, "\t\t\t%s: {\n", typeKey(k))
		for _, e := range docs.Enums[k] {
			fmt.Fprintf(&b, "\t\t\t\t{Doc: %s, Value: %s},\n", strconv.Quote(e.Doc), strconv.Quote(e.Value))
		}
		fmt.Fprintf(&b, "\t\t\t},\n")
	}
	fmt.Fprintf(&b, "\t\t},\n")

	fmt.Fprintf(&b, "\t\tFields: map[configdoc.Key]configdoc.Doc{\n")
	keys := slices.SortedFunc(maps.Keys(docs.Fields), func(a, b configdoc.Key) int {
		return cmp.Or(cmp.Compare(a.Package, b.Package), cmp.Compare(a.Type, b.Type), cmp.Compare(a.Field, b.Field))
	})
	for _, k := range keys {
		d := docs.Fields[k]
		fmt.Fprintf(&b, "\t\t\t{Field: %s, Package: %s, Type: %s}: {", strconv.Quote(k.Field), strconv.Quote(k.Package), strconv.Quote(k.Type))
		var parts []string
		if d.Block {
			parts = append(parts, "Block: true")
		}
		if d.Line != "" {
			parts = append(parts, "Line: "+strconv.Quote(d.Line))
		}
		if d.Text != "" {
			parts = append(parts, "Text: "+strconv.Quote(d.Text))
		}
		fmt.Fprintf(&b, "%s},\n", strings.Join(parts, ", "))
	}
	fmt.Fprintf(&b, "\t\t},\n")

	fmt.Fprintf(&b, "\t\tTypes: map[configdoc.TypeKey]string{\n")
	for _, k := range sortedTypeKeys(docs.Types) {
		fmt.Fprintf(&b, "\t\t\t%s: %s,\n", typeKey(k), strconv.Quote(docs.Types[k]))
	}
	fmt.Fprintf(&b, "\t\t},\n\t}\n}\n")

	out, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("formatting generated source: %w", err)
	}

	return out, nil
}

// walker collects the named types a config reaches, keyed by import path and
// name
type walker struct {
	enums        map[string]map[string]*types.Named
	skipUntagged bool
	structs      map[string]map[string]*types.Named
}

// walk records the named struct and string types t reaches, or returns error
// for a type no config file can describe
func (w *walker) walk(t types.Type) error {
	switch u := t.(type) {
	case *types.Alias:
		return w.walk(types.Unalias(u))
	case *types.Array:
		return w.walk(u.Elem())
	case *types.Map:
		return w.walk(u.Elem())
	case *types.Pointer:
		return w.walk(u.Elem())
	case *types.Slice:
		return w.walk(u.Elem())
	case *types.Struct:
		return fmt.Errorf("anonymous struct %s has no name to key its docs by", u)
	case *types.Named:
		return w.named(u)
	}

	return nil
}

// named records the named type n and walks what it reaches, or returns error
func (w *walker) named(n *types.Named) error {
	obj := n.Obj()
	if obj.Pkg() == nil || standard(obj.Pkg().Path()) {
		// the standard library documents its types for programmers
		return nil
	}
	if n.TypeArgs().Len() > 0 {
		return fmt.Errorf("generic type %s has no name to key its docs by", n)
	}

	path := obj.Pkg().Path()
	switch u := n.Underlying().(type) {
	case *types.Struct:
		if w.structs[path][obj.Name()] != nil {
			return nil
		}
		if w.structs[path] == nil {
			w.structs[path] = map[string]*types.Named{}
		}
		w.structs[path][obj.Name()] = n

		for i := range u.NumFields() {
			f := u.Field(i)
			if !w.configured(f, u.Tag(i)) {
				continue
			}
			if err := w.walk(f.Type()); err != nil {
				return fmt.Errorf("%s.%s: %w", n, f.Name(), err)
			}
		}

	case *types.Basic:
		if u.Info()&types.IsString != 0 {
			if w.enums[path] == nil {
				w.enums[path] = map[string]*types.Named{}
			}
			w.enums[path][obj.Name()] = n
		}

	default:
		return w.walk(u)
	}

	return nil
}

// configured reports whether the field f with the struct tag tag is read from
// a config file, as [configdoc.NewSchema] decides it
func (w *walker) configured(f *types.Var, tag string) bool {
	if !f.Exported() {
		return false
	}

	name, options, _ := strings.Cut(reflect.StructTag(tag).Get("mapstructure"), ",")
	switch {
	case name == "-":
		return false
	case slices.Contains(strings.Split(options, ","), "squash"):
		return true
	case name == "" && w.skipUntagged:
		return false
	}

	return true
}

// packages returns the import paths declaring a recorded type
func (w *walker) packages() map[string]bool {
	out := map[string]bool{}
	for path := range w.structs {
		out[path] = true
	}
	for path := range w.enums {
		out[path] = true
	}

	return out
}

// read adds the docs of the recorded types src declares to result
func (w *walker) read(src *packages.Package, result *Result) {
	for _, file := range src.Syntax {
		for _, decl := range file.Decls {
			gd, ok := decl.(*ast.GenDecl)
			if !ok {
				continue
			}
			switch gd.Tok {
			case token.TYPE:
				w.readTypes(src, file, gd, result)
			case token.CONST:
				w.readConsts(src, gd, result)
			}
		}
	}
}

// readTypes adds the docs of the recorded types declared by gd in file of src
func (w *walker) readTypes(src *packages.Package, file *ast.File, gd *ast.GenDecl, result *Result) {
	for _, spec := range gd.Specs {
		ts := spec.(*ast.TypeSpec)
		name := ts.Name.Name
		_, isStruct := w.structs[src.PkgPath][name]
		_, isEnum := w.enums[src.PkgPath][name]
		if !isStruct && !isEnum {
			continue
		}

		doc := ts.Doc
		if doc == nil && len(gd.Specs) == 1 {
			doc = gd.Doc
		}
		if text := strings.TrimSpace(doc.Text()); text != "" {
			result.Docs.Types[configdoc.TypeKey{Name: name, Package: src.PkgPath}] = text
		}

		st, ok := ts.Type.(*ast.StructType)
		if !ok || !isStruct {
			continue
		}
		named := w.structs[src.PkgPath][name]
		w.readFields(src, file, named, st, result)
	}
}

// readFields adds the docs of the fields of the struct st, which declares
// named, in file of src
func (w *walker) readFields(src *packages.Package, file *ast.File, named *types.Named, st *ast.StructType, result *Result) {
	underlying := named.Underlying().(*types.Struct)
	fset := src.Fset
	prevEnd := fset.Position(st.Fields.Opening).Line

	for _, field := range st.Fields.List {
		start := field.Pos()
		if field.Doc != nil {
			start = field.Doc.Pos()
		}
		block := prevEnd != fset.Position(st.Fields.Opening).Line &&
			blankBetween(fset, file, prevEnd, fset.Position(start).Line)

		end := field.End()
		if field.Comment != nil {
			end = field.Comment.End()
		}
		prevEnd = fset.Position(end).Line

		names := field.Names
		if len(names) == 0 {
			// an embedded field is named after its type
			names = []*ast.Ident{{Name: embeddedName(field.Type)}}
		}
		for _, ident := range names {
			i := slices.IndexFunc(fieldsOf(underlying), func(v *types.Var) bool { return v.Name() == ident.Name })
			if i < 0 || !w.configured(underlying.Field(i), underlying.Tag(i)) {
				continue
			}

			doc := configdoc.Doc{
				Block: block,
				Line:  strings.TrimSpace(field.Comment.Text()),
				Text:  strings.TrimSpace(field.Doc.Text()),
			}
			key := configdoc.Key{Field: ident.Name, Package: src.PkgPath, Type: named.Obj().Name()}
			if doc.Text == "" && !isSquash(underlying.Tag(i)) {
				result.Missing = append(result.Missing, src.PkgPath+"."+key.Type+"."+key.Field)
			}
			if doc != (configdoc.Doc{}) {
				result.Docs.Fields[key] = doc
			}
		}
	}
}

// readConsts adds the constants gd declares of a recorded string type of src
func (w *walker) readConsts(src *packages.Package, gd *ast.GenDecl, result *Result) {
	for _, spec := range gd.Specs {
		vs := spec.(*ast.ValueSpec)
		doc := vs.Doc
		if doc == nil && len(gd.Specs) == 1 {
			doc = gd.Doc
		}

		for _, ident := range vs.Names {
			c, ok := src.TypesInfo.Defs[ident].(*types.Const)
			if !ok || c.Val().Kind() != constant.String {
				continue
			}
			// the types of this pass are not those of the first, so they
			// are matched by name
			named, ok := c.Type().(*types.Named)
			if !ok || named.Obj().Pkg() == nil || named.Obj().Pkg().Path() != src.PkgPath ||
				w.enums[src.PkgPath][named.Obj().Name()] == nil {
				continue
			}

			key := configdoc.TypeKey{Name: named.Obj().Name(), Package: src.PkgPath}
			result.Docs.Enums[key] = append(result.Docs.Enums[key], configdoc.Enum{
				Doc:   strings.TrimSpace(doc.Text()),
				Value: constant.StringVal(c.Val()),
			})
		}
	}
}

// blankBetween reports whether a line after the line from and before the
// line to of file is blank, a line holding a comment not being blank
func blankBetween(fset *token.FileSet, file *ast.File, from, to int) bool {
	occupied := map[int]bool{}
	for _, group := range file.Comments {
		first, last := fset.Position(group.Pos()).Line, fset.Position(group.End()).Line
		if last < from || first > to {
			continue
		}
		for line := first; line <= last; line++ {
			occupied[line] = true
		}
	}
	for line := from + 1; line < to; line++ {
		if !occupied[line] {
			return true
		}
	}

	return false
}

// embeddedName returns the name of an embedded field of type expr
func embeddedName(expr ast.Expr) string {
	switch e := expr.(type) {
	case *ast.StarExpr:
		return embeddedName(e.X)
	case *ast.SelectorExpr:
		return e.Sel.Name
	case *ast.Ident:
		return e.Name
	}

	return ""
}

// fieldsOf returns the fields of s
func fieldsOf(s *types.Struct) []*types.Var {
	out := make([]*types.Var, s.NumFields())
	for i := range s.NumFields() {
		out[i] = s.Field(i)
	}

	return out
}

// isSquash reports whether tag squashes its field into the struct holding it,
// whose fields then document themselves
func isSquash(tag string) bool {
	_, options, _ := strings.Cut(reflect.StructTag(tag).Get("mapstructure"), ",")
	return slices.Contains(strings.Split(options, ","), "squash")
}

// standard reports whether path is a package of the standard library, whose
// first element has no dot
func standard(path string) bool {
	first, _, _ := strings.Cut(path, "/")
	return !strings.Contains(first, ".")
}

// packageErrors returns the errors pkgs were loaded with, if any
func packageErrors(pkgs []*packages.Package) error {
	var errs []error
	packages.Visit(pkgs, nil, func(p *packages.Package) {
		for _, err := range p.Errors {
			errs = append(errs, err)
		}
	})

	return errors.Join(errs...)
}

// sortedTypeKeys returns the keys of m sorted by package and name
func sortedTypeKeys[V any](m map[configdoc.TypeKey]V) []configdoc.TypeKey {
	return slices.SortedFunc(maps.Keys(m), func(a, b configdoc.TypeKey) int {
		return cmp.Or(cmp.Compare(a.Package, b.Package), cmp.Compare(a.Name, b.Name))
	})
}

// typeKey returns k as a composite literal
func typeKey(k configdoc.TypeKey) string {
	return fmt.Sprintf("{Name: %s, Package: %s}", strconv.Quote(k.Name), strconv.Quote(k.Package))
}

// cutLast slices s around the last instance of sep
func cutLast(s, sep string) (string, string, bool) {
	i := strings.LastIndex(s, sep)
	if i < 0 {
		return s, "", false
	}

	return s[:i], s[i+len(sep):], true
}
